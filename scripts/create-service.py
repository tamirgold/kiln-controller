#!/usr/bin/env python3
"""Generate a systemd unit for review. This does not install or start a service."""
import argparse
import os
from pathlib import Path
import pwd
import re
import sys


BOARDS = ("raspberry-pi", "orange-pi-zero-2w")


def quoted(value, *, command=False):
    """Quote one systemd value, including literal specifiers and exec dollars."""
    value = str(value)
    if any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise ValueError("Paths cannot contain control characters.")
    value = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    if command:
        value = value.replace("$", "$$")
    return '"' + value + '"'


def render_service(directory, user, board, mode):
    directory = Path(directory)
    if not directory.is_absolute():
        raise ValueError("The repository directory must be an absolute Linux path.")
    directory_text = str(directory)
    if directory_text != directory_text.rstrip() or any(
            ord(char) < 32 or ord(char) == 127 for char in directory_text):
        raise ValueError("The repository directory cannot contain controls or end in whitespace.")
    if not re.fullmatch(r"[a-z_][a-z0-9_-]*[$]?", user) or user == "root":
        raise ValueError("Use a normal Linux account name, never root.")
    if board not in BOARDS or mode not in ("simulation", "hardware"):
        raise ValueError("Choose an explicit supported board and service mode.")
    python = quoted(directory / "venv/bin/python", command=True)
    controller = quoted(directory / "kiln-controller.py", command=True)
    lines = [
        "# Generated by scripts/create-service.py. Review before installing.",
        "[Unit]",
        f"Description=Kiln controller ({board}, {mode})",
        "Wants=network-online.target",
        "After=network-online.target chrony.service",
        "StartLimitIntervalSec=60",
        "StartLimitBurst=6",
        "",
        "[Service]",
        "Type=simple",
        f"User={user}",
        # This directive takes the full raw path, unlike ExecStart/Environment.
        f"WorkingDirectory={directory_text.replace('%', '%%')}",
        "Environment=PYTHONUNBUFFERED=1",
        f"Environment=KILN_BOARD={board}",
    ]
    if mode == "simulation":
        preview_directory = directory / "storage/preview" / board
        lines += [
            "Environment=KILN_SIMULATE=1",
            "Environment=" + quoted(f"KILN_STATE_FILE={preview_directory}/state.json"),
            "Environment=" + quoted(f"KILN_SETTINGS_FILE={preview_directory}/settings.json"),
            "ExecStartPre=/usr/bin/mkdir -p " + quoted(preview_directory, command=True),
        ]
    else:
        heater_off = quoted(directory / "heater-off.py", command=True)
        lines += [
            "# Simulation follows local Settings. Keep it on until commissioning is complete.",
            "SupplementaryGroups=gpio",
            f"ExecStartPre={python} {heater_off}",
            f"ExecStopPost={python} {heater_off}",
        ]
    lines += [
        f"ExecStart={python} {controller}",
        "Restart=on-failure",
        "RestartSec=5",
        "TimeoutStopSec=45",
        "NoNewPrivileges=true",
        "UMask=0027",
        "LogRateLimitIntervalSec=30s",
        "LogRateLimitBurst=30",
        "",
        "[Install]",
        "WantedBy=multi-user.target",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--board", required=True, choices=BOARDS)
    parser.add_argument("--mode", choices=("simulation", "hardware"), default="simulation")
    parser.add_argument("--user", default=pwd.getpwuid(os.getuid()).pw_name,
                        help="normal account that owns the checkout (default: current account)")
    parser.add_argument("--directory", type=Path, default=Path(__file__).resolve().parents[1],
                        help="absolute checkout path (default: this checkout)")
    parser.add_argument("--output", type=Path,
                        help="create a new file; existing files are never overwritten (default: stdout)")
    parser.add_argument("--commissioned", action="store_true",
                        help="confirm the hardware wiring, off level and commissioning checks were reviewed")
    args = parser.parse_args()
    if args.mode == "hardware" and not args.commissioned:
        parser.error("hardware mode requires --commissioned after the checks in docs/INSTALL.md")
    try:
        content = render_service(args.directory, args.user, args.board, args.mode)
        if args.output:
            with args.output.open("x", encoding="utf-8") as output:
                output.write(content)
            print(f"Created {args.output}. Review before installing; no service has been started.")
        else:
            sys.stdout.write(content)
    except (ValueError, OSError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
